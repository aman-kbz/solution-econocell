# ---------------- helpers ----------------
obj = lambda n: bpy.data.objects[n]
alive = lambda names: [obj(n) for n in names if n in bpy.data.objects]
def dims(n): mn,mx=R.bb[n]; return [mx[i]-mn[i] for i in range(3)]
def set_mat(o, m): o.data.materials.clear(); o.data.materials.append(m)

def face_normal(o):
    me=o.data; nmat=o.matrix_world.to_3x3(); best=None; ba=-1
    for p in me.polygons:
        if p.area>ba: ba=p.area; best=p
    return (nmat@best.normal).normalized()
def plate_axis(n):
    a=[abs(n.x),abs(n.y),abs(n.z)]; return a.index(max(a))

def planar_uv(o, grain):
    """Real-scale planar UV; texture-V (grain) aligned to a world direction in the
    panel plane. Robust to CAD rotation (uses the true face normal).
    The FBX import leaves a junk CAD UV layer behind; it must GO, because glTF gives
    the material TEXCOORD_0 and the junk layer would otherwise win on the website."""
    me=o.data
    for l in [l.name for l in me.uv_layers if l.name != 'UVMap']:
        me.uv_layers.remove(me.uv_layers[l])
    n=face_normal(o); Z=mathutils.Vector((0,0,1))
    if abs(n.z)>0.7:                                   # horizontal plate
        wmn,wmx=roomlib.world_bounds(o); longX = (wmx[0]-wmn[0])>=(wmx[1]-wmn[1])
        if grain=='horizontal_cross': longX = not longX
        Vv = mathutils.Vector((1,0,0)) if longX else mathutils.Vector((0,1,0))
    elif grain=='vertical':
        Vv = (Z - Z.dot(n)*n).normalized()
    else:
        Vv = n.cross(Z).normalized()
    Uu = n.cross(Vv).normalized()
    lay = me.uv_layers.get('UVMap') or me.uv_layers.new(name='UVMap')
    lay.active = lay.active_render = True   # the layer Blender renders == the one we compute,
    uvl = lay.data                          # so phase-2 edits and the GLB can't diverge
    mw = o.matrix_world
    for poly in me.polygons:
        for li in poly.loop_indices:
            co = mw @ me.vertices[me.loops[li].vertex_index].co
            uvl[li].uv = (co.dot(Uu)/TILE_U, co.dot(Vv)/TILE_V)

def coll(name):
    c = bpy.data.collections.get(name) or bpy.data.collections.new(name)
    if name not in [ch.name for ch in bpy.context.scene.collection.children]:
        bpy.context.scene.collection.children.link(c)
    return c
def to_coll(o, name):
    c = coll(name)
    for uc in list(o.users_collection): uc.objects.unlink(o)
    c.objects.link(o)

def fast_merge(objs, name, mat, collname=None):
    """Merge many mesh objects into ONE by concatenating world-space geometry.
    Drops UVs/normals (recomputed) -- fine for SOLID-colour groups (hardware, legs,
    doors, frames). Orders of magnitude faster than bpy.ops.object.join for the
    tens of thousands of hardware objects these CAD exports contain."""
    import numpy as np
    objs=[o for o in objs if o and o.name in bpy.data.objects and o.type=='MESH']
    if not objs: return None
    all_v=[]; all_f=[]; off=0
    for o in objs:
        me=o.data; nv=len(me.vertices)
        if nv==0: continue
        co=np.empty(nv*3, dtype=np.float64); me.vertices.foreach_get('co', co)
        mw=np.array(o.matrix_world)
        world=(co.reshape(-1,3)@mw[:3,:3].T)+mw[:3,3]
        all_v.append(world)
        for p in me.polygons: all_f.append([off+i for i in p.vertices])
        off+=nv
    verts=np.concatenate(all_v).tolist() if all_v else []
    nm=bpy.data.meshes.new(name); nm.from_pydata(verts,[],all_f); nm.update()
    no=bpy.data.objects.new(name,nm); bpy.context.scene.collection.objects.link(no)
    no.data.materials.append(mat)
    bpy.data.batch_remove(objs)                 # fast bulk delete of originals
    if collname: to_coll(no, collname)
    return no

# ---------------- role logic ----------------
def front_face(c):
    cnt=Counter()
    for n in c['names']:
        t=plate_axis(face_normal(obj(n)))
        if t==2: continue
        mn,mx=R.bb[n]; side=1 if (mn[t]+mx[t])/2>c['center'][t] else 0
        inset=(c['mx'][t]-mx[t]) if side==1 else (mn[t]-c['mn'][t])
        if inset<=0.05: cnt[(t,side)]+=1
    return cnt.most_common(1)[0][0] if cnt else (0,0)
def role(n,c,fax,fs):
    t=plate_axis(face_normal(obj(n)))
    if t==2: return 'top_bot'
    mn,mx=R.bb[n]; side=1 if (mn[t]+mx[t])/2>c['center'][t] else 0
    inset=(c['mx'][t]-mx[t]) if side==1 else (mn[t]-c['mn'][t])
    if inset>0.05: return 'drawerbox'
    if t==fax and side==fs: return 'front'
    return 'side' if t!=fax else 'back'

# ---------------- Richelieu 3647 bow pull (160 c-to-c) ----------------
def make_handle():
    """Build one black-plastic bow pull to real dims (metres):
    205 long, 30 wide, 30 projection, 22 finger clearance, 31 feet. Local frame:
    X=length (centred), Y=width (centred), Z=projection out from the face (Z=0=face)."""
    import bmesh
    L2, H, G, f, W2 = 0.1025, 0.030, 0.022, 0.031, 0.015
    pts = [(-L2,0),(-L2,H),(L2,H),(L2,0),(L2-f,0),(L2-f,G),(-(L2-f),G),(-(L2-f),0)]
    bm = bmesh.new()
    vs = [bm.verts.new((x, -W2, z)) for (x,z) in pts]
    bm.faces.new(vs)
    r = bmesh.ops.extrude_face_region(bm, geom=bm.faces[:])
    ev = [e for e in r['geom'] if isinstance(e, bmesh.types.BMVert)]
    bmesh.ops.translate(bm, vec=(0, 2*W2, 0), verts=ev)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
    try: bmesh.ops.bevel(bm, geom=bm.edges[:], offset=0.0025, segments=2, affect='EDGES')
    except Exception: pass
    me = bpy.data.meshes.new("Handle_3647"); bm.to_mesh(me); bm.free()
    for p in me.polygons: p.use_smooth = True
    o = bpy.data.objects.new("Handle_3647", me); bpy.context.scene.collection.objects.link(o)
    o.data.materials.append(M_HANDLE)
    return o

def wcenter(o):
    mn,mx = roomlib.world_bounds(o); return mathutils.Vector([(mn[i]+mx[i])/2 for i in range(3)])

def place_handles(pulls, fronts):
    """Place a 3647 for each wire pull. HORIZONTAL (drawer) pulls are centred on the
    nearest front (the bigger 160mm pull stays centred). VERTICAL (door) pulls keep
    their original position (near the door edge) and run vertically. Handle local axes:
    X=length, Y=width, Z=projection(out)."""
    if not pulls: return
    tmpl = make_handle(); Z = mathutils.Vector((0,0,1))
    for i,(M,is_vert) in enumerate(pulls):
        P = M.translation.copy()
        outw = mathutils.Vector((0,-1,0))
        best = min(fronts, key=lambda o:(wcenter(o)-P).length) if fronts else None
        if best:
            n = face_normal(best); n.z = 0
            if n.length > 1e-6: outw = n.normalized()
        if is_vert:                              # DOOR pull: vertical, keep original spot
            length = Z; pos = P
        else:                                    # DRAWER pull: horizontal, centred on front
            length = Z.cross(outw)
            if length.length < 1e-6: length = mathutils.Vector((1,0,0))
            length.normalize()
            pos = wcenter(best) if best else P
        localY = outw.cross(length).normalized()
        rot = mathutils.Matrix((length, localY, outw)).transposed().to_4x4()
        h = tmpl.copy(); h.data = tmpl.data
        bpy.context.scene.collection.objects.link(h)
        h.matrix_world = mathutils.Matrix.Translation(pos) @ rot
        h.name = f"Handle_{i+1}"; to_coll(h, "Handles")
    bpy.data.objects.remove(tmpl)

# ---------------- classify clusters (robust across file types) ----------------
WINDOWS  = [c['id'] for c in R.clusters if c['kind']=='window']
JUNK     = [c['id'] for c in R.clusters if max(c['size'])<0.15]
# worktop = wide thin slab lifted off the floor (desk surface)
WORKTOPS = [c['id'] for c in R.clusters if c['kind']=='casework' and c['id'] not in JUNK
            and c['size'][2]<0.45 and max(c['size'][0],c['size'][1])>0.8 and 0.25<c['mn'][2]<1.2]
# drawer cabinet = any remaining boxy casework (floor OR wall mounted)
DRAWERS  = [c['id'] for c in R.clusters if c['kind']=='casework'
            and c['id'] not in WORKTOPS and c['id'] not in JUNK
            and min(c['size'])>0.12 and c['size'][2]>0.25]
WALL_SIDES  = R.walls_by_side()
DOOR_NAMES  = [o.name for o in R.shell if R.cat[o.name]=='door']
GLASS_NAMES = [o.name for o in R.shell if R.cat[o.name]=='glass']
STRUCT_NAMES= [o.name for o in R.shell if R.cat[o.name] in ('floor','ceiling')]
COMP_NAMES  = [o.name for o in R.components()]
# wire pulls -> to be swapped for the 3647; record transform + orientation (a pull whose
# longest axis is vertical is a DOOR pull: keep it vertical & near its edge, don't recentre).
PULLS=[]; PULL_MESH=set()
for o in bpy.data.objects:
    if o.type=='EMPTY' and 'PULL' in o.name.upper() and 'WIRE' in o.name.upper():
        mn=[1e9]*3; mx=[-1e9]*3; has=False
        for ch in o.children:
            if ch.type=='MESH':
                PULL_MESH.add(ch.name); has=True
                for c in ch.bound_box:
                    w=ch.matrix_world@mathutils.Vector(c)
                    for i in range(3): mn[i]=min(mn[i],w[i]); mx[i]=max(mx[i],w[i])
        if has:
            d=[mx[i]-mn[i] for i in range(3)]
            PULLS.append((o.matrix_world.copy(), d.index(max(d))==2))  # (matrix, is_vertical)
HW_NAMES    = [o.name for o in R.hardware() if o.name not in PULL_MESH]


# drawer cabinets: per-panel material + grain, kept SEPARATE, role-named, in a collection
FRONT_OBJS=[]
for i,cid in enumerate(DRAWERS, 1):
    c=R.clusters[cid]; fax,fs=front_face(c); cname=f'Cabinet_{i}'
    rc=Counter()
    for n in c['names']:
        rl=role(n,c,fax,fs); o=obj(n)
        if rl=='drawerbox': set_mat(o, M_BLKMAT)
        else:
            set_mat(o, LAM[ROLE_GRAIN[rl][0]]); planar_uv(o, ROLE_GRAIN[rl][1])
        if rl=='front': FRONT_OBJS.append(o)
        rc[rl]+=1; o.name=f"{cname}__{rl}_{rc[rl]}"; to_coll(o, cname)

# worktops: surface + back/modesty panel per WORKTOP_SURFACE / WORKTOP_BACK
for i,cid in enumerate(WORKTOPS, 1):
    cname=f"Worktop_{i}"; rc=Counter()
    for n in R.clusters[cid]['names']:
        d=dims(n); o=obj(n)
        if d.index(min(d))==2:
            set_mat(o, LAM[WORKTOP_SURFACE[0]]); planar_uv(o, WORKTOP_SURFACE[1]); tag='surface'
        else:
            set_mat(o, LAM[WORKTOP_BACK[0]]); planar_uv(o, WORKTOP_BACK[1]); tag='back'
        rc[tag]+=1; o.name=f"{cname}__{tag}_{rc[tag]}"; to_coll(o, cname)

# window: glass panes + aluminium frame (kept separate)
for i,cid in enumerate(WINDOWS, 1):
    cname=f"Window_{i}"; rc=Counter()
    for n in R.clusters[cid]['names']:
        o=obj(n); glass=min(dims(n))<0.03
        set_mat(o, M_GLASS if glass else M_ALU); tag='glass' if glass else 'frame'
        rc[tag]+=1; o.name=f"{cname}__{tag}_{rc[tag]}"; to_coll(o, cname)

# leftover casework (door top-frames etc.) -> aluminium
_placed=set(DRAWERS)|set(WORKTOPS)|set(WINDOWS)|set(JUNK)
_fr=[obj(n) for c in R.clusters if c['kind']=='casework' and c['id'] not in _placed for n in c['names']]
fast_merge(_fr, "DoorFrames", M_ALU, "DoorFrames")

# junk delete
for cid in JUNK:
    for n in R.clusters[cid]['names']:
        if n in bpy.data.objects: bpy.data.objects.remove(obj(n))

# walls: named individually, off-white, kept SEPARATE (web toggles)
sc=Counter()
for side,names in WALL_SIDES.items():
    for n in names:
        o=obj(n); sc[side]+=1; set_mat(o, M_WALL)
        o.name=f"Wall_{side.split('_')[1].capitalize()}"+(f"_{sc[side]}" if len(names)>1 else "")
        to_coll(o, "Walls")

# standalone glass (not in a window cluster) -> glass; floor/ceiling -> off-white
for n in GLASS_NAMES:
    if n in bpy.data.objects: set_mat(obj(n), M_GLASS); to_coll(obj(n), "Glass")
for n in STRUCT_NAMES:
    if n in bpy.data.objects: set_mat(obj(n), M_WALL); to_coll(obj(n), "Structure")

# doors -> aluminium, merged
fast_merge(alive(DOOR_NAMES), "Doors", M_ALU, "Doors")
# legs -> black metal, merged
fast_merge(alive(COMP_NAMES), "Legs", M_BLKMET, "Legs")
# swap wire pulls for the Richelieu 3647 handle
for n in list(PULL_MESH):
    if n in bpy.data.objects: bpy.data.objects.remove(bpy.data.objects[n])
place_handles(PULLS, FRONT_OBJS)
print(f"@@@ placed {len(PULLS)} Richelieu 3647 handles ({sum(1 for _,v in PULLS if v)} vertical/door)")
# hardware -> black metal, merged to one mesh (fast)
print(f"@@@ merging {len(HW_NAMES)} hardware objects...")
fast_merge(alive(HW_NAMES), "Hardware", M_BLKMET, "Hardware")

# catch-all: any mesh still loose in the scene root (unclassified) -> Review
loose=[o for o in list(bpy.context.scene.collection.objects) if o.type=='MESH']
for o in loose:
    if not o.data.materials: set_mat(o, LAM[FALLBACK_LAM])
    to_coll(o, "Review")
if loose: print(f"@@@ {len(loose)} unclassified objects -> 'Review' collection (inspect these)")

meshes=[o for o in bpy.data.objects if o.type=='MESH']
print(f"@@@ scene: {len(meshes)} objects | collections:",
      [c.name for c in bpy.context.scene.collection.children])

# recenter: shift the whole scene so the MIN corner of its bounding box sits at
# world origin (0,0,0), preserving all relative positions (BricsCAD had it offset).
_mn=[1e18]*3
for o in bpy.data.objects:
    if o.type!='MESH': continue
    for c in o.bound_box:
        w=o.matrix_world@mathutils.Vector(c)
        for i in range(3): _mn[i]=min(_mn[i], w[i])
if _mn[0] < 1e17:
    _T=mathutils.Matrix.Translation(mathutils.Vector((-_mn[0],-_mn[1],-_mn[2])))
    for o in bpy.data.objects:
        if o.parent is None: o.matrix_world = _T @ o.matrix_world
    print(f"@@@ recentered: min corner {[round(v,2) for v in _mn]} -> (0,0,0)")

# soft world so Rendered view is lit while hand-editing (NOT exported to GLB;
# model-viewer lights the model with its own environment on the web).
_w = bpy.data.worlds.new("EditWorld"); _w.use_nodes = True
_bg = _w.node_tree.nodes['Background']
_bg.inputs['Color'].default_value = (0.85, 0.86, 0.90, 1.0)
_bg.inputs['Strength'].default_value = 1.3
bpy.context.scene.world = _w

os.makedirs(os.path.dirname(os.path.abspath(BLEND)), exist_ok=True)
bpy.ops.file.pack_all()          # embed textures so the .blend is self-contained
bpy.ops.wm.save_as_mainfile(filepath=os.path.abspath(BLEND))
print("@@@ SAVED", BLEND)
