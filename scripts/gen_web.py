"""PART 4 of the pipeline: generate the static site's room manifest + viewer pages.

Plain python (no Blender):  python scripts/gen_web.py

ROOMS below is the single place a room is declared. Each entry writes
  web/rooms/<key>.html      (mirrors the fbx/ + blend_files/ + web/models/ subdirs)
and rewrites web/assets/rooms.js, which drives the menu on web/index.html.
The page itself is a thin shell: web/assets/viewer.js does the work, so styling or
behaviour changes never mean touching N copies of the same HTML.
"""
import os, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB  = os.path.join(ROOT, "web")

# key (mirrors web/models/<key>.glb) , title
ROOMS = [
    # single room — key set once the FBX arrives (fbx/<key>.fbx -> web/models/<key>.glb)
    ("solution_econocell", "Solution Econocell — Room"),
]

PAGE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} — Solution Econocell</title>
<link rel="icon" href="{root}/assets/favicon.png" type="image/png">
<link rel="icon" href="{root}/assets/favicon.ico" sizes="any">
<link rel="apple-touch-icon" href="{root}/assets/apple-touch-icon.png">
<link rel="stylesheet" href="{root}/assets/site.css">
<script type="module" src="{root}/assets/model-viewer.min.js"></script>
</head>
<!-- generated by scripts/gen_web.py — edit that, not this file -->
<body data-room="{key}" data-root="{root}">

<header class="bar">
  <a class="back" href="{root}/index.html">&larr; Rooms</a>
  <div>
    <h1>{title}</h1>
  </div>
  <div class="spacer"></div>
  <img class="logo" src="{root}/assets/logo.png" alt="Ambienti Moderne">
</header>

<div class="stage">
  <model-viewer
    alt="{title}"
    camera-controls auto-rotate auto-rotate-delay="4000" rotation-per-second="12deg"
    touch-action="pan-y" interaction-prompt="none"
    environment-image="neutral" tone-mapping="neutral"
    exposure="1.1" shadow-intensity="0.65" shadow-softness="0.9"
    min-camera-orbit="auto 15deg 0.3m" max-camera-orbit="auto 88deg 40m"
    min-field-of-view="8deg" max-field-of-view="60deg" interpolation-decay="12" orbit-sensitivity="0.55" zoom-sensitivity="0.6" pan-sensitivity="0.6">
  </model-viewer>

  <aside class="panel" id="panel">
    <button class="panel-head" id="panel-toggle" aria-expanded="true" aria-controls="panel-body">
      <span>View options</span><span class="chev" aria-hidden="true">&#9662;</span>
    </button>
    <div class="panel-body" id="panel-body">
      <div id="groups"></div>
      <div class="actions" id="actions"></div>
      <div class="slider">
        <label for="exposure">Exposure <span id="exposure-val">1.10</span></label>
        <input id="exposure" type="range" min="0.4" max="2" step="0.05" value="1.1">
      </div>
      <div class="rows">
        <label class="row" id="auto-row"><input id="auto" type="checkbox" checked><span>Auto-hide near walls</span></label>
        <label class="row"><input id="spin" type="checkbox" checked><span>Auto-rotate</span></label>
      </div>
    </div>
  </aside>

  <div class="hint">Drag to orbit &middot; scroll to zoom &middot; right-drag to pan &middot; double-click to focus</div>
</div>

<script src="{root}/assets/viewer.js"></script>
</body>
</html>
"""

MANIFEST = """/* GENERATED by scripts/gen_web.py — do not hand-edit; add the room there and re-run.
   `key` mirrors the path under web/models/ (and fbx/, blend_files/), so a room in a
   subdir keeps that subdir everywhere, including web/rooms/<key>.html. */
window.ECP_ROOMS = {rooms};
"""

def main():
    rooms = []
    for key, title in ROOMS:
        depth = key.count("/") + 1              # rooms/<key>.html -> back to web/
        root  = "/".join([".."] * depth)
        path  = os.path.join(WEB, "rooms", *key.split("/")) + ".html"
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(PAGE.format(key=key, title=title, root=root))
        print("wrote", os.path.relpath(path, ROOT).replace("\\", "/"))
        glb = os.path.join(WEB, "models", *key.split("/")) + ".glb"
        if not os.path.exists(glb):
            print("   !! missing model:", os.path.relpath(glb, ROOT).replace("\\", "/"))
        rooms.append({"key": key, "title": title})

    js = os.path.join(WEB, "assets", "rooms.js")
    with open(js, "w", encoding="utf-8") as f:
        f.write(MANIFEST.format(rooms=json.dumps(rooms, indent=2, ensure_ascii=False)))
    print("wrote", os.path.relpath(js, ROOT).replace("\\", "/"), f"({len(rooms)} rooms)")

if __name__ == "__main__":
    main()
