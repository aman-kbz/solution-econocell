"""
PART 1 of the Blender workflow: apply materials + best-effort grain, then save an
EDITABLE .blend. Laminate panels are kept as SEPARATE, role-named objects grouped
in per-unit collections, so grain can be fixed by hand (select panel -> rotate UV).
Hardware/legs/doors are merged (nothing to hand-edit there).

  blender --background --factory-startup --python scripts/build_scene.py -- \
      fbx/administration.fbx blender/administration.blend

Then: open the .blend, rotate grain where wrong / fix any glitched material,
save. Finally run scripts/export_glb.py to produce the GLB.
"""
